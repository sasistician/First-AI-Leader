#!/usr/bin/env node
/*
 * Builds the voice agent's knowledge base from the allowlist in kb/sources.json.
 *
 *   node scripts/build-kb.mjs        (or: npm run kb)
 *
 * Slide decks are split one chunk per <section class="slide">; other HTML by h2/h3;
 * Markdown by headings. Output: api/_data/kb.js (bundled into the Vercel function).
 * Re-run and commit whenever the course content changes.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const COURSE = process.env.COURSE_CONTENT_DIR || path.join(ROOT, '..', 'course_content')
const MAX_CHARS = 1100

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', mdash: '—', ndash: '–', middot: '·', rsquo: '’', lsquo: '‘', rdquo: '”', ldquo: '“', hellip: '…', times: '×', rarr: '→', larr: '←' }

function decode(s) {
  return s
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m)
}

function textOf(html) {
  return decode(html.replace(/<br\s*\/?>/gi, ' ').replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim()
}

function stripNoise(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<svg[\s\S]*?<\/svg>/gi, ' ')
    .replace(/<nav[\s\S]*?<\/nav>/gi, ' ')
    .replace(/<div class="chrome"[\s\S]*?<\/div>/gi, ' ') // slide counters like "№ 01 — 29"
}

function firstHeading(html) {
  const m = html.match(/<h[1-3][^>]*>([\s\S]*?)<\/h[1-3]>/i)
  return m ? textOf(m[1]) : ''
}

// Long sections are split on sentence boundaries so each chunk stays readable.
function split(text, max = MAX_CHARS) {
  if (text.length <= max) return [text]
  const out = []
  let cur = ''
  for (const s of text.split(/(?<=[.!?。！？])\s+/)) {
    if ((cur + ' ' + s).length > max && cur) { out.push(cur.trim()); cur = '' }
    cur += ' ' + s
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

function chunksFromHtml(html) {
  const clean = stripNoise(html)
  const slides = [...clean.matchAll(/<section[^>]*class="[^"]*\bslide\b[^"]*"[^>]*>([\s\S]*?)<\/section>/gi)].map((m) => m[1])
  if (slides.length) {
    return slides.map((s, i) => ({ section: firstHeading(s) || `Slide ${i + 1}`, text: textOf(s) }))
  }
  const body = (clean.match(/<body[^>]*>([\s\S]*)<\/body>/i) || [null, clean])[1]
  const parts = body.split(/(?=<h[23][^>]*>)/i)
  return parts.map((p) => ({ section: firstHeading(p) || 'Introduction', text: textOf(p) }))
}

function chunksFromMarkdown(md) {
  const parts = md.replace(/```[\s\S]*?```/g, ' ').split(/^(?=#{1,3}\s)/m)
  return parts.map((p) => {
    const head = (p.match(/^#{1,3}\s+(.+)$/m) || [null, 'Introduction'])[1]
    const text = p.replace(/^#{1,3}\s+/gm, '').replace(/[*_`>|]/g, ' ').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/\s+/g, ' ').trim()
    return { section: head.replace(/[*_`]/g, '').trim(), text }
  })
}

function resolve(p) {
  if (p.startsWith('site:')) return path.join(ROOT, 'public', p.slice(5))
  if (p.startsWith('repo:')) return path.join(ROOT, p.slice(5))
  if (p.startsWith('course:')) return path.join(COURSE, p.slice(7))
  throw new Error(`source path must start with site:, repo: or course: (${p})`)
}

const { sources } = JSON.parse(fs.readFileSync(path.join(ROOT, 'kb/sources.json'), 'utf8'))
const chunks = []
const used = []
for (const src of sources) {
  const file = resolve(src.path)
  if (!fs.existsSync(file)) {
    console.warn(`  skip ${src.id}: ${file} not found`)
    continue
  }
  const raw = fs.readFileSync(file, 'utf8')
  const sections = file.endsWith('.md') ? chunksFromMarkdown(raw) : chunksFromHtml(raw)
  let n = 0
  for (const { section, text } of sections) {
    if (text.length < 40) continue // headings-only fragments
    for (const piece of split(text)) {
      chunks.push({ id: `${src.id}#${++n}`, source: src.id, section, lang: src.lang, text: piece })
    }
  }
  used.push({ id: src.id, program: src.program, title: src.title, url: src.url, lang: src.lang })
  console.log(`  ${src.id.padEnd(14)} ${String(n).padStart(3)} chunks  ${path.relative(ROOT, file)}`)
}

const out = { builtAt: new Date().toISOString(), sources: used, chunks }
fs.mkdirSync(path.join(ROOT, 'api/_data'), { recursive: true })
fs.writeFileSync(path.join(ROOT, 'api/_data/kb.js'),
  '// Generated by scripts/build-kb.mjs from kb/sources.json. Do not edit.\nexport default ' + JSON.stringify(out) + '\n')
const kb = (JSON.stringify(out).length / 1024).toFixed(0)
console.log(`Built ${chunks.length} chunks from ${used.length} sources → api/_data/kb.js (${kb} KB)`)
